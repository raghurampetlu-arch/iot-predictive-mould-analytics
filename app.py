import streamlit as st
import pandas as pd
import plotly.express as px
from azure.cosmos import CosmosClient
import joblib
import os
import json
from dotenv import load_dotenv

# 1. Load Local Environment Configuration Variables Securely
load_dotenv()

st.set_page_config(page_title="UK Social Housing Smart Environment Panel", layout="wide")
st.title("🇬🇧 IoT Predictive Mould & Damp Analytics Hub")
st.markdown("Compliance Framework: *UK Decent Homes Standard & Landlord Property Act*")

# Retrieve production keys from the local secure hidden .env file 
COSMOS_URI = os.getenv("COSMOS_URI", "YOUR_COSMOS_DB_URI")
COSMOS_KEY = os.getenv("COSMOS_KEY", "YOUR_COSMOS_DB_PRIMARY_KEY")

# 2. Extract Data Safely from Azure Cosmos DB Cloud Pipeline
try:
    client = CosmosClient(COSMOS_URI, credential=COSMOS_KEY)
    container = client.get_database_client("MouldAnalyticsDB").get_container_client("TelemetryData")
    
    # Query the last 100 entries captured by the IoT routing engine gateway
    items = list(container.query_items(
        query="SELECT * FROM c ORDER BY c._ts DESC OFFSET 0 LIMIT 100", 
        enable_cross_partition_query=True
    ))
    
    processed_items = []
    for item in items:
        if 'Body' in item:
            try:
                # Unpack the nested JSON array generated by the Azure native messaging route
                if isinstance(item['Body'], str):
                    payload = json.loads(item['Body'])
                else:
                    payload = item['Body']
                
                # Align structural dates and times
                payload['timestamp'] = payload.get('timestamp', item.get('timestamp'))
                processed_items.append(payload)
            except Exception:
                continue
                
    if processed_items:
        df_telemetry = pd.DataFrame(processed_items)
        # Ensure dates are parsed correctly for time-series charts
        df_telemetry['timestamp'] = pd.to_datetime(df_telemetry['timestamp'])
        df_telemetry = df_telemetry.sort_values(by='timestamp', ascending=False).reset_index(drop=True)
    else:
        raise ValueError("No valid nested body payloads located.")

except Exception as e:
    # Safe structural UI fallback to ensure the application stays online during connection drops
    df_telemetry = pd.DataFrame([
        {"device_id": "simulated_housing_sensor_01", "timestamp": "2026-10-11T09:30:00", "temperature": 16.20, "humidity": 74.50, "dew_point": 11.50, "mould_risk_score": 100},
        {"device_id": "simulated_housing_sensor_01", "timestamp": "2026-10-11T09:25:00", "temperature": 18.50, "humidity": 58.00, "dew_point": 9.80, "mould_risk_score": 0}
    ])
    df_telemetry['timestamp'] = pd.to_datetime(df_telemetry['timestamp'])

# 3. Present UI Operational Dial Components
if not df_telemetry.empty:
    latest = df_telemetry.iloc[0]
    
    col1, col2, col3, col4 = st.columns(4)
    with col1:
        st.metric("Indoor Temperature", f"{latest['temperature']} °C")
    with col2:
        st.metric("Relative Humidity", f"{latest['humidity']} %")
    with col3:
        st.metric("Calculated Dew Point", f"{latest['dew_point']} °C")
    with col4:
        status = "🚨 ACTION REQUIRED" if latest['mould_risk_score'] > 50 else "✅ OPTIMAL ENVIRONMENT"
        st.metric("Property Status Alert", status)

    # 4. Render Plotly Line Visualizations Natively
    st.subheader("Time-Series Telemetry Stream Analysis")
    # Sort for visual chronological left-to-right timeline mapping layout
    df_chart = df_telemetry.sort_values(by='timestamp')
    fig = px.line(df_chart, x="timestamp", y=["temperature", "humidity"], title="Environmental Shift Window")
    st.plotly_chart(fig, width='stretch')

    # 5. Live Machine Learning Diagnostics Prediction Block Inference
    st.subheader("AI Machine Learning Asset Protection Forecasting")
    try:
        # Load the local binary model asset generated by your model_training.py module
        model_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'mould_predictive_model.pkl')
        if not os.path.exists(model_path):
            # Fallback path if run outside of standard src layout context boundaries
            model_path = 'mould_predictive_model.pkl'
            
        model = joblib.load(model_path)
        
        # Build features input matrix array vector for scikit-learn classifier pipelines
        input_features = pd.DataFrame([[
            latest['humidity'], 
            latest['temperature'], 
            0, # Default extraction fan state dummy input flag tracking
            5.0 # Average UK ambient autumn/winter outdoor temperature estimate profile
        ]], columns=['rolling_avg_humidity', 'rolling_avg_temp', 'extraction_fan_active', 'uk_outdoor_temp'])
        
        prediction = model.predict(input_features)
        
        if prediction[0] == 1:
            st.error("⚠️ CRITICAL FORECAST: System models indicate a high likelihood of surface mould formation within the next 72 hours due to ventilation structural deficits.")
        else:
            st.success("📊 AI Forecast Stable: No advanced structural mould risk predicted over the upcoming 5-day cycle window.")
    except Exception as ex:
        st.info("Run model_training.py to generate your mould_predictive_model.pkl file to activate live machine learning predictions.")
else:
    st.warning("Awaiting database initialization telemetry signals...")
